import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { findPackageJSON } from 'node:module';
import { dirname, join } from 'node:path';
import { defaultIconNames, iconDataNames } from '../src/icon-catalog.ts';

const version = '1.52.0';
const directory = new URL('../templates/angular/icons/', import.meta.url);
const check = process.argv.includes('--check');
const header = `// Generated by scripts/render-icon-data.mjs from @lucide/icons@${version}.\n`;
const manifest = findPackageJSON('@lucide/icons', import.meta.url);
const installed = JSON.parse(await readFile(manifest, 'utf8'));
if (installed.name !== '@lucide/icons' || installed.version !== version) {
  throw new Error(`Expected @lucide/icons@${version} to generate icon data.`);
}

if (!check) await mkdir(directory, { recursive: true });
async function emit(path, source) {
  if (check) {
    if (await readFile(path, 'utf8') !== source) {
      throw new Error(`Outdated ${path.pathname}. Run node scripts/render-icon-data.mjs.`);
    }
  } else {
    await writeFile(path, source);
  }
}

for (const name of iconDataNames) {
  const { default: data } = await import(`@lucide/icons/icons/${name}`);
  if (data.name !== name || !Array.isArray(data.node)) throw new Error(`Unexpected icon data: ${name}`);
  const record = JSON.stringify(data, null, 2);
  await emit(new URL(`${name}.ts`, directory), `${header}import type { UiIconData } from './registry';\n\nexport const shape: UiIconData = ${record};\n`);
}

const identifier = name => name.replace(/-([a-z])/g, (_, char) => char.toUpperCase());
const imports = defaultIconNames.map(name => `import { shape as ${identifier(name)} } from './${name}';`);
await emit(new URL('defaults.ts', directory), `${header}import type { Provider } from '@angular/core';
import { selected, type UiIconInput } from './registry';
${imports.join('\n')}

/** Register the twelve foundation icons, followed by application overrides. */
export function provideUiIcons(...icons: UiIconInput[]): Provider {
  return selected(${defaultIconNames.map(identifier).join(', ')}, ...icons);
}
`);

const sourceLicense = await readFile(join(dirname(manifest), 'LICENSE'), 'utf8');
await emit(new URL('../assets/third-party/LUCIDE-LICENSE.txt', import.meta.url), sourceLicense);
