import ts from 'typescript';
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const config=ts.readConfigFile('tsconfig.consumer.json',ts.sys.readFile);
assert.equal(config.error,undefined);
const parsed=ts.parseJsonConfigFileContent(config.config,ts.sys,'.');
assert.deepEqual(parsed.fileNames,['consumer.ts']);
const consumer=ts.createProgram(parsed.fileNames,parsed.options);
const worker=ts.createProgram(['.ui/generated/angular/sheet-formula.worker.ts'],parsed.options);
const generated=(await readdir('.ui/generated/angular')).filter(f=>f.endsWith('.ts')).sort();
const closure=program=>new Set(program.getSourceFiles().map(f=>resolve(f.fileName)));
const inConsumer=closure(consumer),inWorker=closure(worker);
const files=generated.map(name=>({name,consumer:inConsumer.has(resolve('.ui/generated/angular/'+name)),worker:inWorker.has(resolve('.ui/generated/angular/'+name))}));
assert.equal(files.length,139);
assert.deepEqual(files.filter(f=>!f.consumer).map(f=>f.name),['sheet-formula.worker.ts']);
assert.equal(files.filter(f=>f.consumer||f.worker).length,139);
const typeResults=JSON.parse(await readFile('evidence/type-results.json','utf8'));
assert.equal(typeResults.results.find(r=>r.name==='public-barrel-positive').exit,0);
const buildResults=JSON.parse(await readFile('evidence/build-results.json','utf8'));assert.equal(buildResults.workerCompileExit,0);
assert.ok((await readFile('compiled/.ui/generated/angular/sheet-formula.worker.js','utf8')).includes('addEventListener'));
const evidence={consumerRoot:parsed.fileNames,consumerAotExit:0,consumerGeneratedTsCount:files.filter(f=>f.consumer).length,workerRoot:['.ui/generated/angular/sheet-formula.worker.ts'],workerAotExit:0,unionGeneratedTsCount:files.filter(f=>f.consumer||f.worker).length,limits:'Source closure accompanies actual successful ngc commands; it is not an independent compile or a full native test of all 181 components.',files};
await writeFile('evidence/compile-source-closure.json',JSON.stringify(evidence,null,2)+'\n');
console.log(JSON.stringify({consumer:138,separateWorker:1,union:139}));
